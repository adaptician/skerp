#!/usr/bin/env node
// sync-to-claude.mjs
// ---------------------------------------------------------------------------
// Mirrors the canonical project skills in `.agents/skills/` into
// `.claude/skills/` so Claude Code can discover them. Codex reads the
// canonical `.agents/skills/` copies directly; Claude Code only scans
// `.claude/skills/`, hence the mirror. See `.agents/skills/README.md`.
//
// Usage:
//   node .agents/skills/sync-to-claude.mjs            # write the mirror
//   node .agents/skills/sync-to-claude.mjs --check     # verify only, no writes
//   node .agents/skills/sync-to-claude.mjs --prune     # also delete orphaned mirrors
//   node .agents/skills/sync-to-claude.mjs --help
//
// Exit codes:
//   0  success (write mode), or mirror already in sync (--check)
//   1  mirror is stale or orphaned (--check), or an error occurred
// ---------------------------------------------------------------------------

import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..", ".."); // .agents/skills -> repo root
const SRC_DIR = path.join(REPO_ROOT, ".agents", "skills");
const DEST_DIR = path.join(REPO_ROOT, ".claude", "skills");

const args = new Set(process.argv.slice(2));
const CHECK = args.has("--check");
const PRUNE = args.has("--prune");
if (args.has("--help") || args.has("-h")) {
  console.log(
    [
      "Mirror .agents/skills/* -> .claude/skills/* (Claude Code discovery).",
      "",
      "  --check   verify the mirror is current; exit 1 if stale (no writes)",
      "  --prune   delete mirrored skills that no longer exist in .agents/skills",
      "  --help    show this message",
    ].join("\n"),
  );
  process.exit(0);
}

const stripBom = (s) => s.replace(/^﻿/, "");

const TEXT_EXT = /\.(md|mjs|js|ts|json|txt|ya?ml|css|scss|html)$/i;
/** Compare content, ignoring line-ending style for text files. */
function sameContent(a, b, rel) {
  if (TEXT_EXT.test(rel)) {
    const norm = (buf) => buf.toString("utf8").replace(/\r\n/g, "\n");
    return norm(a) === norm(b);
  }
  return a.equals(b);
}

/** Build the MIRROR banner for a given skill, pointing at its canonical file. */
function banner(skillName) {
  return [
    "<!--",
    "  MIRROR — do not edit here.",
    `  Canonical source: .agents/skills/${skillName}/SKILL.md`,
    "  Generated by .agents/skills/sync-to-claude.mjs. Claude Code discovers",
    "  skills under .claude/skills/; Codex reads .agents/skills/ directly.",
    "  Edit the canonical file, then re-run the sync tool.",
    "-->",
    "",
  ].join("\n");
}

/** Insert the banner immediately after the YAML frontmatter block. */
function withBanner(content, skillName) {
  const text = stripBom(content);
  const fm = text.match(/^---\r?\n[\s\S]*?\r?\n---\r?\n/);
  if (!fm) {
    // No frontmatter detected — prepend the banner so the warning is visible.
    return banner(skillName) + "\n" + text;
  }
  const head = fm[0];
  const rest = text.slice(head.length).replace(/^\r?\n/, "");
  return head + "\n" + banner(skillName) + "\n" + rest;
}

async function listSkillDirs(dir) {
  let entries;
  try {
    entries = await fs.readdir(dir, { withFileTypes: true });
  } catch {
    return [];
  }
  const out = [];
  for (const e of entries) {
    if (!e.isDirectory()) continue;
    const skillFile = path.join(dir, e.name, "SKILL.md");
    try {
      await fs.access(skillFile);
      out.push(e.name);
    } catch {
      // Not a skill folder (no SKILL.md) — ignore.
    }
  }
  return out.sort();
}

/** Recursively gather files under a dir as paths relative to it. */
async function walk(dir, base = dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files = [];
  for (const e of entries) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) files.push(...(await walk(full, base)));
    else files.push(path.relative(base, full));
  }
  return files.sort();
}

/** Desired mirror content for one file (banner only applied to SKILL.md). */
async function desiredContent(skill, relPath) {
  const raw = await fs.readFile(path.join(SRC_DIR, skill, relPath));
  if (relPath === "SKILL.md") {
    return Buffer.from(withBanner(raw.toString("utf8"), skill), "utf8");
  }
  return raw; // supporting files copied verbatim
}

async function readMaybe(file) {
  try {
    return await fs.readFile(file);
  } catch {
    return null;
  }
}

async function main() {
  const skills = await listSkillDirs(SRC_DIR);
  const stale = [];
  const written = [];

  for (const skill of skills) {
    const relFiles = await walk(path.join(SRC_DIR, skill));
    for (const rel of relFiles) {
      const want = await desiredContent(skill, rel);
      const destFile = path.join(DEST_DIR, skill, rel);
      const have = await readMaybe(destFile);
      const inSync = have && sameContent(have, want, rel);
      if (inSync) continue;

      if (CHECK) {
        stale.push(`${skill}/${rel}`);
      } else {
        await fs.mkdir(path.dirname(destFile), { recursive: true });
        await fs.writeFile(destFile, want);
        written.push(`${skill}/${rel}`);
      }
    }
  }

  // Detect mirrors that no longer have a canonical source.
  const mirrored = await listSkillDirs(DEST_DIR);
  const orphans = mirrored.filter((m) => !skills.includes(m));
  for (const orphan of orphans) {
    if (PRUNE && !CHECK) {
      await fs.rm(path.join(DEST_DIR, orphan), { recursive: true, force: true });
      written.push(`(pruned) ${orphan}/`);
    }
  }

  if (CHECK) {
    const problems = [...stale, ...orphans.map((o) => `${o}/ (orphaned mirror)`)];
    if (problems.length) {
      console.error("Mirror is OUT OF SYNC:");
      for (const p of problems) console.error("  - " + p);
      console.error("\nRun: node .agents/skills/sync-to-claude.mjs");
      process.exit(1);
    }
    console.log(`Mirror is in sync (${skills.length} skill(s)).`);
    return;
  }

  if (written.length) {
    console.log("Mirrored to .claude/skills/:");
    for (const w of written) console.log("  - " + w);
  } else {
    console.log(`Already in sync (${skills.length} skill(s)); nothing to write.`);
  }
  if (orphans.length && !PRUNE) {
    console.log(
      "\nOrphaned mirrors (canonical removed) — re-run with --prune to delete:",
    );
    for (const o of orphans) console.log("  - " + o + "/");
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
